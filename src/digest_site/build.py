"""Site build orchestration: catalog check -> docs -> topic pages -> library -> home -> front door."""

from __future__ import annotations

import fcntl
import importlib
import json
import re
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path

from . import catalog, data, docs, shell
from .shell import Links
from .sitemap import BY_SLUG, LEGACY, PAGE_SLUGS, TOPIC_SLUGS

DIGEST = data.DIGEST
SITE = data.SITE


@dataclass
class BuildContext:
    """Passed to every page's build(ctx)."""

    links: Links  # hrefs relative to digest/site/pages/
    digest: Path
    site: Path

    # convenience wrappers, so page modules need only ctx
    def doc(self, md_name: str) -> str:
        return self.links.doc(md_name)

    def raw(self, digest_path: str) -> str:
        return self.links.raw(digest_path)

    def page(self, slug: str) -> str:
        return self.links.page(slug)

    def repo(self, repo_path: str) -> str:
        return self.links.repo(repo_path)


def _module(slug: str):
    return importlib.import_module(f"digest_site.pages.{slug}")


def _clean(directory: Path) -> None:
    """Remove generated HTML only (never data/ or assets/)."""
    if directory.exists():
        shutil.rmtree(directory)
    directory.mkdir(parents=True)


FRONT_DOOR = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="refresh" content="0; url=site/index.html">
<link rel="icon" href="data:,">
<title>Novo research digest</title>
</head>
<body>
<p>The research digest lives at <a href="site/index.html">site/index.html</a>.
Every file in this folder is catalogued in its <a href="site/pages/library.html">Evidence library</a>.</p>
</body>
</html>
"""

SITE_README = """# Research digest site (generated)

Open `index.html` (or `../index.html`, which redirects here). Everything in this folder except
`assets/` and `data/` is generated by

    .venv/bin/python scripts/build_digest_site.py          # build
    .venv/bin/python scripts/build_digest_site.py export   # refresh data/ snapshots from checkpoints/, then build

- `pages/<slug>.html`: the site pages, built by `src/digest_site/pages/<slug>.py`; the old stage-page
  URLs (pipeline, data, text, adaptation, probes, encoders, finetune) are redirect stubs to their new home
- `docs/<name>.html`: every `digest/*.md`, rendered in the site shell
- `assets/`: shared `site.css`, `site.js`, `charts.js` (hand-owned)
- `data/`: JSON snapshots of gitignored run histories (written only by `export`)

Every file in `digest/` must have a row in `src/digest_site/catalog.py`; the build fails otherwise.
"""


REDIRECT = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<link rel="icon" href="data:,">
<title>Moved · Novo research digest</title>
<script>
(function () {{
  var where = {where};
  var id = decodeURIComponent((location.hash || '').slice(1));
  location.replace((where[id] || '{fallback}') + (id && where[id] ? '#' + id : '#part-{slug}'));
}})();
</script>
</head>
<body><p>This page moved to <a href="{fallback}#part-{slug}">{fallback}</a>.</p></body>
</html>
"""


def _redirects(ids_by_page: dict[str, list[str]]) -> None:
    """Old stage-page URLs (README, markdown, bookmarks) forward to the section's new page, anchor preserved."""
    shared = {sid: f"{slug}.html" for slug, ids in ids_by_page.items() for sid in ids}
    for slug, (home, _) in LEGACY.items():
        # an id that exists on this legacy page's new home wins (e.g. finetune#curves -> phase2, not recipe)
        where = {**shared, **{sid: f"{home}.html" for sid in ids_by_page.get(home, [])}}
        (SITE / "pages" / f"{slug}.html").write_text(
            REDIRECT.format(where=json.dumps(where, sort_keys=True), fallback=f"{home}.html", slug=slug))


def build() -> None:
    """Serialised with an exclusive lock: chains and monitors may rebuild concurrently, and the build rm -rf's pages/."""
    SITE.mkdir(parents=True, exist_ok=True)
    with open(SITE.parent / ".site-build.lock", "w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        _build()


def _build() -> None:
    stale = catalog.check_complete(DIGEST)
    for path in stale:
        data.warn(f"catalog row {path} has no file in digest/")
    SITE.mkdir(parents=True, exist_ok=True)
    for d in ("pages", "docs"):
        _clean(SITE / d)

    ctx = BuildContext(links=Links("pages"), digest=DIGEST, site=SITE)
    summaries, ids_by_page = {}, {}
    for slug in PAGE_SLUGS:
        mod = _module(slug)
        page = mod.build(ctx)
        html = shell.render_page(slug, page, ctx.links, with_evidence=(slug in TOPIC_SLUGS))
        ids = re.findall(r'<(?:section|div) class="(?:card[^"]*|part-divider)" id="([^"]+)"', html)
        dupes = sorted({i for i in ids if ids.count(i) > 1})
        if dupes:
            raise SystemExit(f"Build failed: {slug} has duplicate section ids {dupes}")
        ids_by_page[slug] = ids
        (SITE / "pages" / f"{slug}.html").write_text(html)
        if slug in TOPIC_SLUGS:
            s = dict(mod.summary())
            s.setdefault("stage", BY_SLUG[slug].number)
            summaries[slug] = s

    _redirects(ids_by_page)

    from . import home  # built last, from the summaries

    (SITE / "index.html").write_text(home.render(summaries))
    (SITE / "README.md").write_text(SITE_README)
    front = DIGEST / "index.html"
    if not front.exists() or front.read_text() != FRONT_DOOR:
        front.write_text(FRONT_DOOR)

    # docs last, so links from markdown into the freshly built pages resolve
    dead = docs.render_all(DIGEST, SITE / "docs")
    dead_total = sum(dead.values())
    n_docs = len(dead)
    print(f"site built: {len(PAGE_SLUGS)} pages + home, {n_docs} docs, {len(catalog.ENTRIES)} catalog rows"
          + (f"; {dead_total} dead links in source markdown rendered as plain text" if dead_total else ""),
          file=sys.stderr)
